size = num*2 - 1
for i in range(size):
    if i < num:
        string = ['//Python'] * (i+1) + ['//\n']
    elif num <= i < size-1:
        string = ['//Python'] * (num*2 - i - 1) + ['//\n']
    else:
        string = ['//Python'] * (num*2 - i - 1) + ['//']
    string = ''.join(string)
    with open(file_path, 'a') as file:  # a - add new line
        file.write(string)

